const asyncHandler = require("../middlewares/asyncHandler");
const router = require("express").Router();
const checkAuth = require("../middlewares/checkAuth");
const allowRoles = require("../middlewares/allowRoles");
const controller = require("../controllers/superAdminController");
router.use(checkAuth, allowRoles("super_admin"));
router.get("/overview", asyncHandler(controller.overview));
router.get("/analytics", asyncHandler(controller.overview));
router.get("/departments", asyncHandler(controller.listDepartments));
router.post("/departments", asyncHandler(controller.createDepartment));
router.patch("/departments/:id", asyncHandler(controller.updateDepartment));
router.get("/admins", asyncHandler(controller.listAdmins));
router.post("/admins", asyncHandler(controller.createAdmin));
router.post("/admins/:id/replace", asyncHandler(controller.replaceAdmin));
router.post("/admins/:id/reset-password", asyncHandler(controller.resetAdminPassword));
router.patch("/admins/:id", asyncHandler(controller.changeAdmin));
router.get("/unassigned", asyncHandler(controller.unassigned));
router.patch("/assign/:type/:id", asyncHandler(controller.assignRecord));
router.get("/audit", asyncHandler(controller.listAudit));
module.exports = router;
